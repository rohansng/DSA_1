#include <iostream>
using namespace std;

int main (){
    // output 
    cout << "Hello world!" << endl;
    cout << "Welcome to c++ programming!" << endl;

    // Single input 
    int x;
    cout << "Enter value of x: ";
    cin >> x;
    cout << "Value of x is: " << x << endl;

    // Multiple input
    int a,    b;
    cout << "Enter value of a and b: ";
    cin >> a >> b;
    cout << "Value of a is: " << a << endl;
    cout << "Value of b is: " << b << endl;
    return 0;
}