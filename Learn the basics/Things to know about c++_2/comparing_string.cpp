#include <bits/stdc++.h>
using namespace std;
int main() {
    string s1 = "Hello";
    string s2 = "World";

    // Compare two strings using ==
    if (s1 == s2) {
        cout << "Strings are equal." << endl;
    } else {
        cout << "Strings are not equal." << endl;
    }

    return 0;
}

