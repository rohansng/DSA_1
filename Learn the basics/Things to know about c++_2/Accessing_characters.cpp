#include <bits/stdc++.h>
using namespace std;

int main() {
    string s = "Hello";
    // Accessing individual characters using index
    cout << "First character: " << s[0] << endl; // Output: H
    cout << "Second character: " << s[1] << endl; // Output: e
    cout << "Third character: " << s[2] << endl; // Output: l
    cout << "Fourth character: " << s[3] << endl; // Output: l
    cout << "Fifth character: " << s[4] << endl; // Output : o 

    return 0;
}