#include <iostream>
using namespace std;

int main() {

    // A for loop has three parts:
    // 1. Initialization
    // 2. Condition
    // 3. Increment/Decrement

    for (int i = 1; i <= 10; i++) {

        // This code executes once in every iteration
        cout << "Hey, Striver, this is the "
             << i << "'th iteration" << endl;
    }

    return 0;
}